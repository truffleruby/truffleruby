        if n < 128
          n
        else
          n -= 128
          shift = 0
          while (b = (io.getbyte or raise)) >= 128
            n += (b - 128) << (shift += 7)
          end
          n + (b << (shift + 7))
        end
      end

      #: () -> Integer
      def load_varsint
        n = load_varuint
        (n >> 1) ^ (-(n & 1))
      end

      #: () -> Integer
      def load_integer
        negative = io.getbyte != 0
        length = load_varuint

        value = 0
        length.times { |index| value |= (load_varuint << (index * 32)) }

        value = -value if negative
        value
      end

      #: () -> Float
      def load_double
        (io.read(8) or raise).unpack1("D") #: Float
      end

      #: () -> bool
